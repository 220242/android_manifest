#!/usr/bin/env bash
#
# Put the F-Droid client into the AOSP tree as a prebuilt system app.
#
#   usage: fetch-fdroid.sh <tree-dir>
#
# Called by place-device.sh, so it runs before every stage that reads the device
# tree - the module probe included. It writes, under <tree>/vendor/edge1/fdroid/:
#
#   F-Droid.apk   the client, as f-droid.org publishes it (signed by F-Droid)
#   Android.mk    the FDroid module: a presigned prebuilt app on /product
#   fdroid.mk     PRODUCT_PACKAGES += FDroid, which device.mk pulls in with
#                 inherit-product-if-exists
#
# Nothing else in the build refers to F-Droid by name, so when the download fails
# the directory is simply not there and the image is built without it - a warning
# here, not a failed build. That is also why device.mk does not list FDroid itself:
# the probe stops the run on any PRODUCT_PACKAGES name that matches no module.
#
# The APK is fetched once into ~/.cache/edge1 and reused; EDGE1_FDROID_REFRESH=1
# fetches the current release again. It is accepted only if its signing certificate
# is F-Droid's (SHA-256 below, as published on f-droid.org), so a truncated
# download or anything that is not F-Droid's own build never reaches the image.
set -euo pipefail

readonly TREE="${1:?usage: fetch-fdroid.sh <tree-dir>}"
readonly URL="https://f-droid.org/F-Droid.apk"
readonly CERT_SHA256="43238d512c1e5eb2d6569f4a3afbf5523418b82e0a3ed1552770abb9a9c9ccab"
readonly CACHE="${XDG_CACHE_HOME:-$HOME/.cache}/edge1"
readonly CACHED="$CACHE/F-Droid.apk"
readonly DST="$TREE/vendor/edge1/fdroid"

warn() { echo "fetch-fdroid: $*" >&2; }

# SHA-256 of the APK's (v1, JAR) signing certificate, lower case, no colons.
cert_sha256() {
    local apk="$1" sig keytool
    sig="$(unzip -Z1 "$apk" 2>/dev/null | grep -E '^META-INF/[^/]+\.(RSA|EC|DSA)$' | head -n1 || true)"
    if [[ -n "$sig" ]] && command -v openssl >/dev/null; then
        unzip -p "$apk" "$sig" \
            | openssl pkcs7 -inform DER -print_certs 2>/dev/null \
            | openssl x509 -noout -fingerprint -sha256 2>/dev/null \
            | sed -E 's/.*=//; s/://g' | tr 'A-F' 'a-f'
        return
    fi
    keytool="$(ls "$TREE"/prebuilts/jdk/jdk*/linux-x86/bin/keytool 2>/dev/null | tail -n1 || true)"
    if [[ -n "$keytool" ]]; then
        "$keytool" -printcert -jarfile "$apk" 2>/dev/null \
            | sed -nE 's/^[[:space:]]*SHA256: //p' | head -n1 | tr -d ':' | tr 'A-F' 'a-f'
    fi
}

drop() {
    warn "$*"
    warn "the image is built WITHOUT F-Droid this time"
    rm -rf "$DST"
    exit 0
}

mkdir -p "$CACHE"
if [[ ! -s "$CACHED" || "${EDGE1_FDROID_REFRESH:-0}" == 1 ]]; then
    echo "fetch-fdroid: downloading $URL"
    if ! curl -fsSL --retry 3 --connect-timeout 20 -o "$CACHED.part" "$URL"; then
        rm -f "$CACHED.part"
        [[ -s "$CACHED" ]] || drop "download failed and nothing is cached"
        warn "download failed; using the cached copy"
    else
        mv -f "$CACHED.part" "$CACHED"
    fi
fi

got="$(cert_sha256 "$CACHED")"
if [[ "$got" != "$CERT_SHA256" ]]; then
    rm -f "$CACHED"
    drop "F-Droid.apk is not signed by F-Droid (certificate SHA-256 '${got:-unreadable}')"
fi

mkdir -p "$DST"
# Rewritten only when different, so an unchanged APK does not touch mtimes and
# make the build reinstall it.
if ! cmp -s "$CACHED" "$DST/F-Droid.apk"; then
    cp -f "$CACHED" "$DST/F-Droid.apk"
fi
write_if_changed() {   # $1 file; content on stdin
    local tmp; tmp="$(mktemp)"; cat > "$tmp"
    if cmp -s "$tmp" "$1"; then rm -f "$tmp"; else mv -f "$tmp" "$1"; fi
}
write_if_changed "$DST/Android.mk" <<'EOF'
# Generated by build/fetch-fdroid.sh in the edge1 manifest repo. Do not edit.
LOCAL_PATH := $(call my-dir)

include $(CLEAR_VARS)
LOCAL_MODULE := FDroid
LOCAL_MODULE_CLASS := APPS
LOCAL_MODULE_SUFFIX := $(COMMON_ANDROID_PACKAGE_SUFFIX)
LOCAL_SRC_FILES := F-Droid.apk
# F-Droid's own signature: it has to stay, or F-Droid could not update itself.
LOCAL_CERTIFICATE := PRESIGNED
LOCAL_PRODUCT_MODULE := true
# A prebuilt APK: no dexpreopt, and no build-time check of its <uses-library>
# list against a LOCAL_USES_LIBRARIES nobody wrote.
LOCAL_DEX_PREOPT := false
LOCAL_ENFORCE_USES_LIBRARIES := false
include $(BUILD_PREBUILT)
EOF
write_if_changed "$DST/fdroid.mk" <<'EOF'
# Generated by build/fetch-fdroid.sh in the edge1 manifest repo. Do not edit.
PRODUCT_PACKAGES += FDroid
EOF
echo "fetch-fdroid: F-Droid ($(du -h "$DST/F-Droid.apk" | cut -f1), signature verified) -> vendor/edge1/fdroid"
