#!/usr/bin/env bash
#
# The two things about a build that belong to whoever builds it, not to the tree:
#
# 1. Region. The box comes up in the language and time zone of the machine it was
#    built on, instead of US English and GMT (card 18's getprop: persist.sys.timezone
#    GMT - a TV box has no network time zone to learn it from). The time zone is
#    WSL's own, which WSL keeps equal to Windows'; the language is Windows' display
#    language, asked through WSL's interop. EDGE1_TIMEZONE (an IANA name, e.g.
#    Europe/Moscow) and EDGE1_LOCALE (e.g. ru-RU) override either; "none" leaves
#    Android's default. Written to vendor/edge1/region/region.mk, which edge1_tv.mk
#    inherits before anything else, so its locale comes first in PRODUCT_LOCALES -
#    the first one is the default. Both are only defaults: Settings changes them.
#
# 2. Signing keys. Every APK and the platform itself were signed with AOSP's test
#    keys, whose private halves are published in build/make/target/product/security:
#    anyone can sign an app as "platform" and be given what the platform signature
#    grants. This makes a key set of this machine's own, once, in
#    ~/android_khadas/keys (EDGE1_KEYS_DIR), copies it to vendor/edge1-priv/keys
#    in the tree, and edge1_tv.mk signs with it when it is complete (ro.build.tags
#    becomes dev-keys). Keep that directory: an install signed with one set cannot
#    be updated in place by a build signed with another - a fresh flash always
#    works. EDGE1_TEST_KEYS=1 goes back to the test keys.
#
#   usage: build/local-config.sh <tree-dir>        (place-device.sh runs it)
set -euo pipefail
readonly TREE="${1:?usage: local-config.sh <tree-dir>}"

say()  { echo "local-config: $*"; }
# Warnings on stdout too: the Windows transcript keeps stdout, not stderr.
warn() { echo "local-config: WARNING: $*"; }

# Writes $2 to $1 only when different, so an unchanged config is not a new input.
write_if_changed() {
    local f="$1" tmp
    tmp="$(mktemp)"
    cat > "$tmp"
    if [[ -f "$f" ]] && cmp -s "$tmp" "$f"; then rm -f "$tmp"; else mkdir -p "$(dirname "$f")"; mv "$tmp" "$f"; fi
}

# ---- region ------------------------------------------------------------------
tz="${EDGE1_TIMEZONE:-}"
if [[ -z "$tz" ]]; then
    tz="$(readlink -f /etc/localtime 2>/dev/null | sed -n 's#^.*/zoneinfo/##p')"
fi
case "$tz" in
    none|UTC|Etc/*|"") tz="" ;;
esac
if [[ -n "$tz" && ! "$tz" =~ ^[A-Za-z_]+(/[A-Za-z0-9_+-]+)+$ ]]; then
    warn "time zone '$tz' does not look like an IANA name; not setting one"
    tz=""
fi

loc="${EDGE1_LOCALE:-}"
if [[ -z "$loc" ]]; then
    ps=/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe
    if [[ -x "$ps" ]]; then
        loc="$(timeout 60 "$ps" -NoProfile -NonInteractive -Command \
               '[Globalization.CultureInfo]::CurrentUICulture.Name' 2>/dev/null | tr -d '\r\n ' || true)"
    fi
fi
case "$loc" in
    none|en-US|"") loc="" ;;
esac
if [[ -n "$loc" && ! "$loc" =~ ^[a-z]{2,3}-[A-Z]{2}$ ]]; then
    warn "locale '$loc' is not of the form ll-CC; not setting one"
    loc=""
fi

{
    echo "# Generated by build/local-config.sh in the edge1 manifest repo. Do not edit;"
    echo "# set EDGE1_LOCALE / EDGE1_TIMEZONE for the build instead."
    [[ -n "$loc" ]] && echo "PRODUCT_LOCALES := ${loc/-/_}"
    [[ -n "$tz" ]] && echo "PRODUCT_PRODUCT_PROPERTIES += persist.sys.timezone=$tz"
    true
} | write_if_changed "$TREE/vendor/edge1/region/region.mk"
say "region: language ${loc:-Android default}, time zone ${tz:-Android default}"

# ---- signing keys ------------------------------------------------------------
readonly KEYS="${EDGE1_KEYS_DIR:-$HOME/android_khadas/keys}"
readonly TREE_KEYS="$TREE/vendor/edge1-priv/keys"
# Every certificate name a module may ask for relative to the default one, as
# LineageOS generates them for the same release.
readonly NAMES="releasekey platform shared media networkstack sdk_sandbox bluetooth nfc testkey"

if [[ "${EDGE1_TEST_KEYS:-0}" == 1 ]]; then
    rm -rf "$TREE_KEYS"
    say "keys: AOSP test keys (EDGE1_TEST_KEYS=1)"
    exit 0
fi

make_key="$TREE/development/tools/make_key"
mkdir -p "$KEYS"
chmod 700 "$KEYS"
for n in $NAMES; do
    [[ -f "$KEYS/$n.pk8" && -f "$KEYS/$n.x509.pem" ]] && continue
    if [[ ! -x "$make_key" ]] || ! command -v openssl >/dev/null; then
        warn "keys: cannot make $n (no development/tools/make_key or openssl); the build uses the test keys"
        rm -rf "$TREE_KEYS"
        exit 0
    fi
    rm -f "$KEYS/$n.pk8" "$KEYS/$n.x509.pem"
    # make_key asks for a password; an empty line means none (the build cannot
    # type one in). The subject only names the key. Its exit status says nothing:
    # its EXIT trap ends in "exit 1" whatever happened, so the files are the test.
    ( cd "$KEYS" && echo | "$make_key" "$n" "/C=XX/O=Khadas Edge1 Android TV/CN=$n" ) >/dev/null 2>&1 || true
    if [[ ! -s "$KEYS/$n.pk8" || ! -s "$KEYS/$n.x509.pem" ]] \
       || ! openssl x509 -noout -in "$KEYS/$n.x509.pem" 2>/dev/null; then
        warn "keys: make_key failed for $n; the build uses the test keys"
        rm -f "$KEYS/$n.pk8" "$KEYS/$n.x509.pem"
        rm -rf "$TREE_KEYS"
        exit 0
    fi
    say "keys: made $n"
done

mkdir -p "$TREE_KEYS"
for n in $NAMES; do
    for ext in pk8 x509.pem; do
        cmp -s "$KEYS/$n.$ext" "$TREE_KEYS/$n.$ext" || cp -f "$KEYS/$n.$ext" "$TREE_KEYS/$n.$ext"
    done
done
chmod 600 "$TREE_KEYS"/*.pk8
say "keys: this machine's own, from $KEYS (back that directory up)"
